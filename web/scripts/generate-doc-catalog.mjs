import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const repositoryRoot = path.resolve(scriptDirectory, "../..");
const docsRoot = path.join(repositoryRoot, "docs");
const outputPath = path.join(repositoryRoot, "web/src/generated/docs-catalog.ts");
const collectionNames = {
  ai: "AI",
  "cloud-native": "Cloud Native",
  data: "Data",
  dotnet: ".NET",
  "software-architecture": "Software Architecture",
};

const displayName = value => value
  .replace(/\.md$/i, "")
  .replace(/[-_]+/g, " ")
  .replace(/\b\w/g, character => character.toUpperCase());

const resourceTypes = ["Articles", "Videos", "Libraries", "Samples", "Resources", "Books"];
const resourceTypeForHeading = heading => {
  const normalized = heading.toLowerCase();
  if (normalized.includes("video")) return "Videos";
  if (normalized.includes("library") || normalized.includes("tool")) return "Libraries";
  if (normalized.includes("sample") || normalized.includes("example")) return "Samples";
  if (normalized.includes("book")) return "Books";
  if (normalized.includes("resource")) return "Resources";
  return "Articles";
};
const countFileResources = file => {
  const source = fs.readFileSync(path.join(repositoryRoot, file.path), "utf8");
  const counts = Object.fromEntries(resourceTypes.map(type => [type, 0]));
  let currentType = "Articles";
  for (const line of source.split(/\r?\n/)) {
    const heading = /^(#{1,6})\s+(.+?)\s*$/.exec(line);
    if (heading) {
      const label = heading[2].replace(/[#*_`]/g, "").replace(/^(?:📕|📦|📺|🚀|📘|📚|📝|📹)\s*/u, "").trim();
      currentType = resourceTypeForHeading(label);
    } else if (/^\s*[-*]\s+\[[^\]]+\]\(https?:\/\/[^)]+\)/.test(line)) {
      counts[currentType] += 1;
    }
  }
  return counts;
};
const resourceCounts = node => [...node.files, ...node.folders.flatMap(resourceFiles)].reduce((total, file) => {
  const counts = countFileResources(file);
  for (const type of resourceTypes) total[type] += counts[type];
  return total;
}, Object.fromEntries(resourceTypes.map(type => [type, 0])));
const resourceFiles = node => [...node.files, ...node.folders.flatMap(resourceFiles)];

const readNode = relativeDirectory => {
  const absoluteDirectory = path.join(docsRoot, relativeDirectory);
  const entries = fs.readdirSync(absoluteDirectory, { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name));
  const files = entries
    .filter(entry => entry.isFile() && entry.name.toLowerCase().endsWith(".md"))
    .map(entry => ({
      name: displayName(entry.name),
      path: path.posix.join("docs", relativeDirectory.replaceAll(path.sep, "/"), entry.name),
    }));
  const folders = entries
    .filter(entry => entry.isDirectory())
    .map(entry => readNode(path.join(relativeDirectory, entry.name)));
  return {
    name: displayName(path.basename(relativeDirectory)),
    path: path.posix.join("docs", relativeDirectory.replaceAll(path.sep, "/")),
    files,
    folders,
  };
};

const catalog = Object.entries(collectionNames).map(([slug, name]) => ({
  name,
  slug,
  ...readNode(slug),
  resourceCounts: resourceCounts(readNode(slug)),
}));

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, `// Generated by scripts/generate-doc-catalog.mjs. Do not edit.\nexport type DocFile = { name: string; path: string };\nexport type DocFolder = { name: string; path: string; files: DocFile[]; folders: DocFolder[] };\nexport type ResourceCounts = Record<"Articles" | "Videos" | "Libraries" | "Samples" | "Resources" | "Books", number>;\nexport type DocCollection = DocFolder & { name: string; slug: string; resourceCounts: ResourceCounts };\nexport const docsCatalog: DocCollection[] = ${JSON.stringify(catalog, null, 2)};\n`);